"""Generate a standalone ``pipeline.py`` that reproduces a run's cross-validation score.

The script embeds :mod:`holdout.core.portable` verbatim (minus its module docstring) plus
the run's configuration as literals. It therefore imports only the standard library,
pandas, numpy, scikit-learn and lightgbm, and rebuilds the split and pipeline with the very
code Holdout used. Generation is deterministic: no timestamps, sorted literals, LF line
endings, so the same plan always gives a byte-identical file.
"""

import ast
import pprint
from pathlib import Path

from holdout import __version__
from holdout.core import config, portable
from holdout.core.errors import ExportError
from holdout.core.seeds import derive_seed
from holdout.data.profile import DatasetProfile
from holdout.data.split import SplitSpec
from holdout.plan.compiler import plan_to_config
from holdout.plan.schema import ModelPlan


def render_pipeline_script(
    *,
    plan: ModelPlan,
    profile: DatasetProfile,
    spec: SplitSpec,
    data_sha256: str,
) -> str:
    """Return the source of a standalone script reproducing ``plan``'s CV score.

    Raises:
        PlanValidationError: if the plan is invalid for ``profile``.
    """
    pipeline_config = plan_to_config(plan, profile, run_seed=spec.seed)
    split_config = spec.to_config()
    # v1.1: a plan that deduplicates development rows reproduces that step too.
    dedup = (
        [f"DEDUP_SIGNIFICANT_DIGITS = {config.ROW_HASH_SIGNIFICANT_DIGITS}", ""]
        if plan.deduplicate
        else []
    )
    dedup_arg = ["            dedup_significant_digits=DEDUP_SIGNIFICANT_DIGITS,"] * bool(dedup)
    sections = [
        _header(plan, spec),
        _kernel_source(),
        "\n# ---------------------------------------------------------------- run configuration\n",
        f"DATA_SHA256 = {data_sha256!r}",
        f"TARGET = {profile.target!r}",
        f"METRIC = {plan.metric.value!r}",
        f"N_SPLITS = {config.N_FOLDS}",
        f"CV_SEED = {derive_seed(spec.seed, 'cv')}",
        "",
        f"SPLIT_CONFIG: SplitConfig = {_literal(split_config)}",
        "",
        f"PIPELINE_CONFIG: PipelineConfig = {_literal(pipeline_config)}",
        "",
        *dedup,
        "",
        'if __name__ == "__main__":',
        "    raise SystemExit(",
        "        run_exported_cv(",
        "            None,",
        "            data_sha256=DATA_SHA256,",
        "            target=TARGET,",
        "            metric=METRIC,",
        "            n_splits=N_SPLITS,",
        "            cv_seed=CV_SEED,",
        "            split_config=SPLIT_CONFIG,",
        "            pipeline_config=PIPELINE_CONFIG,",
        *dedup_arg,
        "        )",
        "    )",
        "",
    ]
    return "\n".join(sections)


def write_pipeline_script(
    path: Path, *, plan: ModelPlan, profile: DatasetProfile, spec: SplitSpec, data_sha256: str
) -> Path:
    """Render and write the script with LF line endings (byte-identical across platforms)."""
    source = render_pipeline_script(plan=plan, profile=profile, spec=spec, data_sha256=data_sha256)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(source)
    return path


def _header(plan: ModelPlan, spec: SplitSpec) -> str:
    lines = [
        '"""Standalone reproduction of a Holdout cross-validation run.',
        "",
        f"Generated by holdout {__version__} from a validated ModelPlan. Regenerate rather than",
        "edit: the configuration below is exactly what the run evaluated.",
        "",
        "    python pipeline.py --csv <the CSV the run used>",
        "",
        f"It re-applies the recorded {spec.strategy.value} split, discards the holdout rows",
        f"unseen, rebuilds the pipeline and prints the {plan.metric.value} cross-validation score",
        "on the development rows. It imports pandas, numpy, scikit-learn and lightgbm only.",
        '"""',
        "",
        "# Plan rationale (one line per choice):",
    ]
    lines += [f"#   {field}: {text}" for field, text in plan.rationale.model_dump().items()]
    if plan.drop_columns:
        lines.append("# Dropped columns:")
        lines += [f"#   {d.column!r}: {d.reason}" for d in plan.drop_columns]
    if plan.deduplicate:
        lines.append("# Duplicate development rows are removed before cross-validation.")
    return "\n".join(lines) + "\n"


def _kernel_source() -> str:
    """The portable kernel's source without its module docstring."""
    source = Path(portable.__file__).read_text(encoding="utf-8")
    tree = ast.parse(source)
    first = tree.body[0] if tree.body else None
    if not (
        isinstance(first, ast.Expr)
        and isinstance(first.value, ast.Constant)
        and isinstance(first.value.value, str)
        and first.end_lineno is not None
    ):
        raise ExportError("portable.py must start with a module docstring")
    body = source.splitlines()[first.end_lineno :]
    return "\n".join(body).strip("\n") + "\n"


def _literal(value: object) -> str:
    """A deterministic Python literal: sorted keys, stable float repr."""
    return pprint.pformat(value, sort_dicts=True, width=88)
